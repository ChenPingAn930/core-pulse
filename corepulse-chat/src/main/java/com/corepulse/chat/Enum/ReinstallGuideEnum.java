package com.corepulse.chat.Enum;

import lombok.Getter;

/**
 * 重装系统图文引导枚举
 * <p>
 * 集中管理「重装系统」场景的完整引导文案，供 LLM 在用户提出重装需求时，
 * 按固定流程输出：环境检测 → 数据备份提醒 → 下载官方工具 → 图文制作U盘 → 安装指引。
 * <p>
 * 能力边界（重要）：
 * 1. 本引导只负责制作「系统安装 U 盘」并指引用户完成安装，不代替用户执行
 *    分区、格式化 C 盘、安装、修改引导等危险操作。
 * 2. 使用微软官方「Media Creation Tool」制作启动盘，最可靠、最安全。
 * 3. 制作启动盘会清空 U 盘数据，必须前置提醒用户。
 */
@Getter
public enum ReinstallGuideEnum {

    /**
     * 环境检测引导：让 LLM 先用终端命令检测本机环境，确认能否制作启动盘
     */
    ENV_CHECK("""
            检测电脑是否满足制作系统安装 U 盘的条件，按以下顺序用终端命令(runShellCommand)逐项检查：

            1. 系统版本与位数（决定下载 32/64 位工具）：
               wmic os get Caption,OSArchitecture

            2. U 盘是否插入及容量（需 8GB 以上）：
               wmic logicaldisk where DriveType=2 get DeviceID,Size,FreeSpace

            3. U 盘物理信息（确认是移动设备）：
               wmic diskdrive where MediaType="Removable Media" get Model,Size

            检查结果用表格呈现，例如：

            | 检查项 | 结果 | 是否通过 |
            |--------|------|---------|
            | 系统版本 | Windows 11 专业版 64位 | 是 |
            | U 盘 | 已插入，32GB | 是 |

            若 U 盘未插入或容量不足 8GB，先提醒用户准备一个空 U 盘（8GB 以上），不要继续下一步。
            """),

    /**
     * 数据备份提醒：重装前必须备份，绝不跳过
     */
    BACKUP_REMIND("""
            在制作启动盘之前，必须向用户强调数据安全（极其重要）：

            1. 明确告知：重装系统会清空 C 盘以及安装系统的硬盘分区，桌面、文档、下载、软件
               配置等数据都会丢失，且不可恢复。

            2. 请用户先自行备份重要数据，建议备份到：移动硬盘、U盘、
               或网盘。

            3. 询问用户"是否已经备份好重要数据"。只有用户明确回答已备份，才能继续下一步；
               如果用户还没备份，引导他先完成备份，不要催促。

            输出格式（禁止 emoji / 加粗 / 分隔线）：

            | 建议备份的内容 | 备份到哪里 |
            |----------------|-----------|
            | 桌面文件 | D盘 / 网盘 |
            | 文档(Documents) | D盘 / 网盘 |
            | 下载(Downloads) | D盘 / 网盘 |
            | 浏览器收藏夹与密码 | 导出为文件 |
            | 微信/QQ聊天记录 | 自带的迁移功能 |

            备份完成后，询问用户确认，得到确认后再进入下一步。
            """),

    /**
     * 下载微软官方工具引导
     */
    DOWNLOAD_MCT("""
            引导用户下载微软官方的「媒体创建工具（Media Creation Tool）」来制作系统安装 U 盘。
            这是微软官方工具，最可靠、最安全，不使用任何第三方工具。

            下载方式（告诉用户，不要用终端命令下载）：
            1. 打开微软官网下载页面：
               https://www.microsoft.com/zh-cn/software-download/windows11
               （如果是 Windows 10 系统，把 windows11 换成 windows10）
            2. 页面下拉到「创建 Windows 11 安装媒体」区域
            3. 点击「立即下载」，会得到一个 MediaCreationTool.exe（或类似名称）文件
            4. 保存到桌面或任意文件夹，双击运行

            请把官方下载地址原样展示给用户，并告诉他下载完成后双击运行该工具，
            然后进入下一步。
            """),

    /**
     * 图文制作U盘引导（核心步骤）
     */
    MAKE_USB_GUIDE("""
            引导用户在微软「媒体创建工具」中完成制作启动 U 盘，按以下步骤清晰输出。
            每步都给出"做什么 + 在哪里点"的说明，让普通用户能照着操作：

            第1步：同意许可条款
            打开工具后，勾选"接受"，点击"下一步"。

            第2步：选择语言和版本
            默认已勾选"使用适用于此电脑的推荐选项"，直接点"下一步"即可。
            如需修改语言，取消勾选后手动选择中文。

            第3步：选择要使用的介质
            选择"U 盘"这一项，点击"下一步"。

            第4步：选择 U 盘
            在列表里选中插入的 U 盘（注意核对容量，别选错），点击"下一步"。

            第5步：开始下载并写入
            工具会自动下载系统镜像并写入 U 盘，这个过程需要较长时间（可能 10-30 分钟），
            期间保持 U 盘连接、不要断电、不要拔 U 盘，耐心等待完成。

            第6步：完成
            看到"你的 U 盘已就绪"提示后，点击"完成"。此时 U 盘已经是可启动的系统安装盘。

            关键提醒（必须输出）：
            - 整个过程会清空 U 盘里的所有数据，请确保 U 盘上没有要保留的文件
            - 写入期间不要拔 U 盘、不要关机
            - 完成后先安全弹出 U 盘
            """),

    /**
     * 安装系统引导：控制权交给用户，明确能力边界
     */
    INSTALL_GUIDE("""
            启动盘制作完成后，引导用户进行系统安装。明确告诉用户：从这里开始的操作需要
            用户在重启后的安装环境中手动完成，本助手无法远程执行。

            安装步骤（清晰输出给用户）：

            第1步：保持 U 盘插入，重启电脑
            第2步：进入引导菜单
            开机时按启动热键（不同品牌不同：华硕/技嘉 F8，微星/戴尔 F11，联想 F12，惠普 F9，
            宏碁 F12），或在 BIOS 里把 U 盘设置为第一启动项。
            第3步：选择 U 盘启动
            在引导菜单里选择 U 盘（通常显示品牌型号或 USB 字样）。
            第4步：进入 Windows 安装程序
            选择语言/时间/输入法，点击"下一步" → "现在安装"。
            第5步：选择"自定义：仅安装 Windows"
            选择要安装系统的分区，可以删除原系统分区后新建（会清空该分区数据，确认无误再操作）。
            第6步：等待安装
            系统自动复制文件、安装、重启数次，按屏幕提示操作即可。
            第7步：完成初始设置
            设置区域、键盘、账户、网络，等待进入桌面。

            安装完成后提醒：首次进系统后装好显卡/声卡等驱动，并检查重要数据是否已备份到位。
            """);

    /** 枚举名称 */
    private final String content;

    ReinstallGuideEnum(String content) {
        this.content = content;
    }
}
